CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS auth;

---------------------------------------------------------------------------------------------------
CREATE TABLE auth.tenants
(
    tenant_id       VARCHAR(36)  NOT NULL,

    deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    company_name    VARCHAR(255) NOT NULL,
    company_code    VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    status          VARCHAR(50)  NOT NULL DEFAULT 'PENDING',

    admin_full_name VARCHAR(255) NOT NULL,
    admin_email     VARCHAR(255) NOT NULL,
    admin_username  VARCHAR(255) NOT NULL,
    admin_password  VARCHAR(255) NOT NULL,

    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    created_by      UUID,
    updated_by      UUID,

    CONSTRAINT pk_tenants
        PRIMARY KEY (tenant_id),

    CONSTRAINT uk_tenants_company_code
        UNIQUE (company_code),

    CONSTRAINT uk_tenants_email
        UNIQUE (email),

    CONSTRAINT uk_tenants_admin_email
        UNIQUE (admin_email),

    CONSTRAINT uk_tenants_admin_username
        UNIQUE (admin_username),

    CONSTRAINT chk_tenants_status
        CHECK (
            status IN (
                       'PENDING',
                       'PROVISIONING',
                       'APPROVED',
                       'ACTIVE',
                       'SUSPENDED',
                       'INACTIVE'
                )
            )
);

---------------------------------------------------------------------------------------------------
CREATE TABLE auth.users
(
    user_id                 UUID         NOT NULL,
    tenant_id               VARCHAR(36),
    username                VARCHAR(255) NOT NULL,
    email                   VARCHAR(255) NOT NULL,
    password                VARCHAR(255) NOT NULL,
    first_name              VARCHAR(255) NOT NULL,
    last_name               VARCHAR(255) NOT NULL,

    enabled                 BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted                 BOOLEAN      NOT NULL DEFAULT FALSE,
    scheduled_deletion_at   TIMESTAMPTZ,
    account_non_expired     BOOLEAN      NOT NULL DEFAULT TRUE,
    account_non_locked      BOOLEAN      NOT NULL DEFAULT TRUE,
    credentials_non_expired BOOLEAN      NOT NULL DEFAULT TRUE,

    version                 BIGINT       NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    created_by              UUID,
    updated_by              UUID,

    CONSTRAINT pk_users
        PRIMARY KEY (user_id),

    CONSTRAINT fk_users_tenant
        FOREIGN KEY (tenant_id)
            REFERENCES auth.tenants (tenant_id),

    CONSTRAINT uk_users_tenant_username
        UNIQUE (tenant_id, username),

    CONSTRAINT uk_users_tenant_email
        UNIQUE (tenant_id, email)
);

CREATE INDEX idx_users_tenant_id
    ON auth.users (tenant_id);

CREATE INDEX idx_users_tenant_enabled
    ON auth.users (tenant_id, enabled);

CREATE INDEX idx_users_scheduled_deletion
    ON auth.users (scheduled_deletion_at);

---------------------------------------------------------------------------------------------------
CREATE TABLE auth.roles
(
    role_id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name        VARCHAR(255)                            NOT NULL,
    description VARCHAR(255)                            NOT NULL,

    version     BIGINT                                  NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ                             NOT NULL,
    updated_at  TIMESTAMPTZ                             NOT NULL,
    created_by  UUID,
    updated_by  UUID,

    CONSTRAINT pk_roles
        PRIMARY KEY (role_id),

    CONSTRAINT uk_roles_name
        UNIQUE (name)
);

---------------------------------------------------------------------------------------------------
CREATE TABLE auth.user_roles
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id    UUID                                    NOT NULL,
    role_id    BIGINT                                  NOT NULL,

    version    BIGINT                                  NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ                             NOT NULL,
    updated_at TIMESTAMPTZ                             NOT NULL,
    created_by UUID,
    updated_by UUID,

    CONSTRAINT pk_user_roles
        PRIMARY KEY (id),

    CONSTRAINT fk_user_role_user
        FOREIGN KEY (user_id)
            REFERENCES auth.users (user_id)
            ON DELETE CASCADE,

    CONSTRAINT fk_user_role_role
        FOREIGN KEY (role_id)
            REFERENCES auth.roles (role_id),

    CONSTRAINT uk_user_role_user_role
        UNIQUE (user_id, role_id)
);

CREATE INDEX idx_user_roles_user_id
    ON auth.user_roles (user_id);

CREATE INDEX idx_user_roles_role_id
    ON auth.user_roles (role_id);

---------------------------------------------------------------------------------------------------
CREATE TABLE auth.refresh_tokens
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    jti               VARCHAR(128)                            NOT NULL,
    user_id           UUID                                    NOT NULL,
    expires_at        TIMESTAMPTZ                             NOT NULL,
    revoked           BOOLEAN                                 NOT NULL DEFAULT FALSE,
    replaced_by_token VARCHAR(128),

    version           BIGINT                                  NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ                             NOT NULL,
    updated_at        TIMESTAMPTZ                             NOT NULL,
    created_by        UUID,
    updated_by        UUID,

    CONSTRAINT pk_refresh_tokens
        PRIMARY KEY (id),

    CONSTRAINT uk_refresh_tokens_jti
        UNIQUE (jti),

    CONSTRAINT fk_refresh_token_user
        FOREIGN KEY (user_id)
            REFERENCES auth.users (user_id)
            ON DELETE CASCADE
);

CREATE INDEX idx_refresh_token_user
    ON auth.refresh_tokens (user_id);

CREATE INDEX idx_refresh_token_expires_at
    ON auth.refresh_tokens (expires_at);

CREATE INDEX idx_refresh_token_revoked_expires
    ON auth.refresh_tokens (revoked, expires_at);

CREATE INDEX idx_refresh_token_user_active
    ON auth.refresh_tokens (user_id, expires_at)
    WHERE revoked = FALSE;

