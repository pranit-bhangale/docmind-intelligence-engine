CREATE TABLE IF NOT EXISTS users
(
    user_id                 UUID         NOT NULL,
    tenant_id               VARCHAR(36)  NOT NULL,
    username                VARCHAR(255) NOT NULL,
    email                   VARCHAR(255) NOT NULL,
    password                VARCHAR(255) NOT NULL,
    first_name              VARCHAR(255) NOT NULL,
    last_name               VARCHAR(255) NOT NULL,

    enabled                 BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted                 BOOLEAN      NOT NULL DEFAULT FALSE,
    scheduled_deletion_at   TIMESTAMPTZ,
    account_non_expired     BOOLEAN      NOT NULL DEFAULT TRUE,
    account_non_locked      BOOLEAN      NOT NULL DEFAULT TRUE,
    credentials_non_expired BOOLEAN      NOT NULL DEFAULT TRUE,

    version                 BIGINT       NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    created_by              UUID,
    updated_by              UUID,

    CONSTRAINT pk_users
    PRIMARY KEY (user_id),

    CONSTRAINT fk_users_tenant
    FOREIGN KEY (tenant_id)
    REFERENCES auth.tenants (tenant_id),

    CONSTRAINT uk_users_tenant_username
    UNIQUE (tenant_id, username),

    CONSTRAINT uk_users_tenant_email
    UNIQUE (tenant_id, email)
    );

CREATE INDEX IF NOT EXISTS idx_users_tenant_id
    ON users (tenant_id);

CREATE INDEX IF NOT EXISTS idx_users_tenant_enabled
    ON users (tenant_id, enabled);

CREATE INDEX IF NOT EXISTS idx_users_scheduled_deletion
    ON users (scheduled_deletion_at);

