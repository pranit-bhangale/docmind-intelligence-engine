CREATE TABLE IF NOT EXISTS refresh_tokens
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    jti               VARCHAR(128)                            NOT NULL,
    user_id           UUID                                    NOT NULL,
    expires_at        TIMESTAMPTZ                             NOT NULL,
    revoked           BOOLEAN                                 NOT NULL DEFAULT FALSE,
    replaced_by_token VARCHAR(128),

    version           BIGINT                                  NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ                             NOT NULL,
    updated_at        TIMESTAMPTZ                             NOT NULL,
    created_by        UUID,
    updated_by        UUID,

    CONSTRAINT pk_refresh_tokens
    PRIMARY KEY (id),

    CONSTRAINT uk_refresh_tokens_jti
    UNIQUE (jti),

    CONSTRAINT fk_refresh_token_user
    FOREIGN KEY (user_id)
    REFERENCES users (user_id)
    ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_refresh_token_user
    ON refresh_tokens (user_id);

CREATE INDEX IF NOT EXISTS idx_refresh_token_expires_at
    ON refresh_tokens (expires_at);

CREATE INDEX IF NOT EXISTS idx_refresh_token_revoked_expires
    ON refresh_tokens (revoked, expires_at);

CREATE INDEX IF NOT EXISTS idx_refresh_token_user_active
    ON refresh_tokens (user_id, expires_at)
    WHERE revoked = FALSE;

